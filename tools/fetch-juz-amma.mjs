// Saves Juz 'Amma (surahs 78-114) into js/quran-juz-amma.js so the app has the text offline.
//   node tools/fetch-juz-amma.mjs
// Text: Tanzil Quran Text (Simple), via the alquran.cloud service (edition quran-simple). It is kept exactly as
// published; only the basmala that alquran.cloud puts in front of each first ayah is taken off again, because in
// the Tanzil text the basmala is not part of the ayah (the app shows it on its own line).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// the basmala exactly as this edition writes it: Al-Fatiha, ayah 1
const fatiha = (await (await fetch("https://api.alquran.cloud/v1/ayah/1:1/quran-simple")).json()).data;
const BASMALA = fatiha.text.trim();
if (!BASMALA.startsWith("بِسْمِ")) throw new Error("unexpected basmala");
// all of juz 30 in one request (the service limits how often it may be asked)
const res = await fetch("https://api.alquran.cloud/v1/juz/30/quran-simple");
if (!res.ok) throw new Error(`juz 30: ${res.status}`);
const juz = (await res.json()).data;
if (juz.edition.identifier !== "quran-simple") throw new Error("unexpected edition");
const out = [];
juz.ayahs.forEach((a) => {
  let s = out[out.length - 1];
  if (!s || s.n !== a.surah.number) { s = { n: a.surah.number, name: a.surah.name, count: a.surah.numberOfAyahs, ayat: [] }; out.push(s); }
  if (a.numberInSurah !== s.ayat.length + 1) throw new Error(`surah ${s.n}: ayah ${a.numberInSurah} out of order`);
  s.ayat.push(a.text);
});
out.forEach((s) => {
  if (s.ayat[0].startsWith(BASMALA + " ")) s.ayat[0] = s.ayat[0].slice(BASMALA.length + 1);
  else throw new Error(`surah ${s.n}: first ayah does not start with the basmala`);
  if (s.ayat.length !== s.count) throw new Error(`surah ${s.n}: ${s.ayat.length} of ${s.count} ayat`);
  delete s.count;
});
if (out.length !== 37 || out[0].n !== 78 || out[36].n !== 114) throw new Error("juz 30 should be surahs 78-114");
const header = `// Juz 'Amma (surahs 78-114). Generated by tools/fetch-juz-amma.mjs — do not edit by hand.
// Tanzil Quran Text (Simple), Copyright (C) 2007-2024 Tanzil Project, https://tanzil.net
// License: Creative Commons Attribution 3.0. The text is used without any change; the basmala is shown separately.
`;
fs.writeFileSync(path.join(root, "js", "quran-juz-amma.js"), header + "window.JUZ_AMMA = " + JSON.stringify(out) + ";\n", "utf8");
console.log(`\nsaved ${out.length} surahs, ${out.reduce((a, s) => a + s.ayat.length, 0)} ayat`);
